from pdxaudit.tracker import get_commits

LAW = "in_game/common/laws/l.txt"
LAW_OLD = ("law_a = {\n\tmodifier = {\n\t\tlocal_monthly_food_modifier = 0.1\n\t\tcost = 1\n\t}\n"
           "\tif = { limit = { has_x = yes } add = 1 }\n"
           "\tif = { limit = { has_y = yes } add = 2 }\n"
           "\tif = { limit = { has_y = yes } add = 3 }\n"
           "\tNOT = { has_z = yes }\n}\n"
           "law_b = {\n\tcost = 5\n\tupkeep = 1\n}\n")
LAW_NEW = LAW_OLD.replace("cost = 1\n", "cost = 2\n")
GUI = "in_game/gui/map_markers.gui"
GUI_OLD = 'types M {\n\ttype marker = widget {\n\t\tmax_update_rate = 4\n\t\tsize = { 1 1 }\n\t}\n}\n'

REGISTRY = """
[system.provisions]
files = ["in_game/**/fe_laws*"]
[system.faster_universalis]
files = ["in_game/gui/**"]
[system.economy]
files = ["in_game/common/laws/m.txt"]
[tool.generate_vanilla_overrides]
path = "tools/generate_vanilla_overrides.py"
status = "active"
"""

MOD_LAWS = ("REPLACE:law_a = {\n\tmodifier = {\n\t\tlocal_monthly_food_modifier = 0\n"
            "\t\tlocal_goods_output_modifier = 0.1\n\t\tcost = 1\n\t}\n"
            "\tif = { limit = { has_x = yes } add = 1 }\n"
            "\tif = { limit = { has_y = yes } add = 2 }\n"
            "\tif = { limit = { has_y = yes } add = 30 }\n"
            "\tnot = { has_z = yes }\n}\n")


def _world(tmp_path, mod_laws=MOD_LAWS, extra=None):
    tr = build_tracker(tmp_path, [
        ("1.0", {LAW: LAW_OLD, GUI: GUI_OLD}),
        ("1.1", {LAW: LAW_NEW, GUI: GUI_OLD}),
    ])
    mod = tmp_path / "mod"
    files = {".metadata/metadata.json": '{"id": "t"}', "pdx-maint.toml": REGISTRY,
             "in_game/common/laws/fe_laws.txt": mod_laws,
             GUI: GUI_OLD.replace("max_update_rate = 4", "max_update_rate = 9999 # [FU]"),
             "in_game/common/laws/m.txt": "INJECT:law_b = {\n\tupkeep = 2\n\tnew_key = yes\n}\n",
             "in_game/common/laws/fe_generated_l.txt":
                 "# AUTO-GENERATED by generate_vanilla_overrides.py from l.txt. Do not hand-edit.\n"}
    files.update(extra or {})
    _write_tree(mod, files)
    commits = get_commits(tr.repo)
    copies, devs = intent.run_collect(mod, VanillaBase(tr.repo), commits, *commits[0])
    return mod, copies, devs


def _dev(devs, **kw):
    hit = [d for d in devs if all(getattr(d, k) == v for k, v in kw.items())]
    assert len(hit) == 1, (kw, [(d.identity, d.path, d.change) for d in devs])
    return hit[0]


def test_deviations_carry_vanilla_identity_and_addresses(tmp_path):
    _mod, _copies, devs = _world(tmp_path)
    food = _dev(devs, mod_key="local_monthly_food_modifier")
    assert food.identity == "in_game/common/laws/law_a" and food.copy == "replace"
    assert [s["key"] for s in food.path] == ["modifier", "local_monthly_food_modifier"]
    assert food.systems == ["provisions"]
    added = _dev(devs, mod_key="local_goods_output_modifier")
    assert added.change == "mod_added" and added.vanilla_text is None


def test_keyword_case_is_no_deviation(tmp_path):
    _mod, _copies, devs = _world(tmp_path)
    assert not [d for d in devs if "NOT" in d.keys or "not" in d.keys]
    assert diff3.nodes("NOT = { a = 1 }")[0].sig == diff3.nodes("not = { a = 1 }")[0].sig


