def test_matcher_fields(tmp_path):
    _mod, _copies, devs = _world(tmp_path)
    food = _dev(devs, mod_key="local_monthly_food_modifier")
    m = lambda **match: intent.rule_matches({"id": "r", "match": match}, food)   # noqa: E731
    assert m(vanilla_key=["re:^(local_|global_)?monthly_food_modifier$"])
    assert m(content=["in_game/common/laws"], audit=["replace"], block=["law_*"])
    assert m(path=["modifier.*"]) and m(path=["**"]) and not m(path=["*"])
    assert m(file=["in_game/common/laws/fe_*.txt"])
    assert m(change=["mod_changed"]) and not m(change=["mod_added"])
    assert m(vanilla_absent=False) and not m(vanilla_absent=True)
    assert m(name=["local_monthly_food_modifier"]) and not m(name=["monthly_food"])


def _rule(**kw):
    rule = {"id": "provisions.food_cancels", "system": "provisions", "reason": "Provisions are the only food.",
            "source": {"kind": "note", "ref": "176"}, "disposition": "keep_mod",
            "match": {"vanilla_key": ["re:^(local_|global_)?monthly_food_modifier$"]}}
    rule.update(kw)
    return rule


def test_store_validation(tmp_path):
    mod, _c, _d = _world(tmp_path)
    reg = Registry(mod)
    state = empty_state()
    intent.add_rule(state, _rule(), reg)
    with pytest.raises(intent.IntentError, match="not a system"):
        intent.add_rule(state, _rule(system="nope"), reg)
    with pytest.raises(intent.IntentError, match="reason"):
        intent.add_rule(state, _rule(reason=" "), reg)
    with pytest.raises(intent.IntentError, match="disposition"):
        intent.add_rule(state, _rule(disposition="maybe"), reg)
    with pytest.raises(intent.IntentError, match="unknown match"):
        intent.add_rule(state, _rule(match={"colour": ["x"]}), reg)
    with pytest.raises(intent.IntentError, match="not a tool"):
        intent.add_rule(state, _rule(tool="nope"), reg)
    intent.add_rule(state, _rule(id="fu", system="faster_universalis", disposition=None,
                                 match={"comment": ["[FU]"]}), reg)      # a grouping
    assert set(intent.of(state)["rules"]) == {"provisions.food_cancels", "fu"}


def test_attribution_entry_over_rule_and_rule_conflicts(tmp_path):
    _mod, copies, devs = _world(tmp_path)
    state = empty_state()
    intent.add_rule(state, _rule())
    food = _dev(devs, mod_key="local_monthly_food_modifier")
    it = intent.of(state)
    assert intent.attribute(food, it).by == "rule:provisions.food_cancels"
    entry = intent.entry_from(food, "e1", "economy", "keep the modifier block", {"kind": "user"},
                              "take_vanilla", depth=1)
    intent.seal(entry, copies, devs)
    intent.add_entry(state, entry)
    a = intent.attribute(food, it, intent.entry_states(it, copies, devs))
    assert (a.by, a.disposition) == ("entry:e1", "take_vanilla")
    added = _dev(devs, mod_key="local_goods_output_modifier")
    assert intent.attribute(added, it).by == "entry:e1"          # the subtree covers it
    intent.remove(state, "e1")
    intent.add_rule(state, _rule(id="other", disposition="take_vanilla"))
    a = intent.attribute(food, it)
    assert a.by is None and a.conflict == ["other", "provisions.food_cancels"]


def test_entry_states(tmp_path):
    _mod, copies, devs = _world(tmp_path)
    d = _dev(devs, mod_value="30")
    state = empty_state()
    entry = intent.entry_from(d, "e1", "economy", "SUL value", {"kind": "user"}, "keep_mod")
    intent.seal(entry, copies, devs)
    intent.add_entry(state, entry)
    it = intent.of(state)
    assert intent.entry_states(it, copies, devs)["e1"] == ("recorded", "")
    # the mod changes the node: stale on the mod side
    _m, copies2, devs2 = _world(tmp_path / "x", mod_laws=MOD_LAWS.replace("add = 30", "add = 31"))
    assert intent.entry_states(it, copies2, devs2)["e1"] == ("stale", "mod changed")
    # the mod drops the REPLACE: the copy is gone
    _m, copies3, devs3 = _world(tmp_path / "y", mod_laws="")
    assert intent.entry_states(it, copies3, devs3)["e1"][0] == "lost"


def test_proposer_groups_and_never_fills_a_reason_from_comments(tmp_path):
    mod, copies, devs = _world(tmp_path)
    notes = [{"id": "176", "title": "t", "body": "- law_a keeps its food modifier: provisions.\n"}]
    cands = proposer.propose(mod, copies, devs, empty_state(), notes, "2026-10-02")
    fu = next(c for c in cands if any(m["identity"].startswith("guifile:") for m in c["members"]))
    assert fu["record"]["reason"] == "" and fu["record"]["source"] == {"kind": "user"}
    assert "[FU]" in fu["evidence"]["comments"]
    law = [c for c in cands if any(m["identity"].endswith("/law_a") for m in c["members"])]
    assert law and all(c["record"]["reason"] == "law_a keeps its food modifier: provisions." for c in law)
    assert all(c["record"]["source"] == {"kind": "note", "ref": "176"} for c in law)
    assert all(c["record"]["disposition"] == "" for c in cands)
    assert not any(m["identity"].startswith("in_game/common/laws/fe_generated") for c in cands
                   for m in c["members"])


def test_accept_needs_a_disposition_and_a_reason(tmp_path):
    mod, copies, devs = _world(tmp_path)
    cands = proposer.propose(mod, copies, devs, empty_state(), [], "2026-10-02")
    path = proposer.write(cands, tmp_path, "t", "1.1", tmp_path / "p.json")
    state = empty_state()
    added, errors = proposer.accept(state, path, ["c1"], Registry(mod))
    assert not added and "choose a disposition" in errors[0]
    doc = json.loads(path.read_text())
    doc["candidates"][0]["record"]["disposition"] = "keep_mod"
    path.write_text(json.dumps(doc))
    added, errors = proposer.accept(state, path, ["c1"], Registry(mod))
    assert not added and "reason" in errors[0]
    doc["candidates"][0]["record"]["reason"] = "SUL design"
    doc["candidates"][0]["record"]["system"] = "economy"
    path.write_text(json.dumps(doc))
    added, errors = proposer.accept(state, path, ["c1", "c99"], Registry(mod))
    assert added and errors == ["c99: no such candidate"]


def test_seeds_from_dismissals_and_the_keep_file(tmp_path):
    mod, copies, devs = _world(tmp_path)
    cost = _dev(devs, mod_key="cost", copy="replace")
    assert cost.change == "vanilla_changed" and cost.finding
    state = empty_state()
    state["dismissed"][cost.finding] = {"finding": "x", "reason": "SUL keeps the old cost"}
    state["dismissed"]["f" * 40] = {"finding": "x"}                  # no reason: no seed
    cands = proposer.seed_dismissals(copies, devs, state, "2026-10-02")
    assert len(cands) == 1 and cands[0]["record"]["reason"] == "SUL keeps the old cost"
    assert cands[0]["record"]["address"]["path"] == cost.path
    keep = tmp_path / "keep.txt"
    keep.write_text("# comment\nlaw_a.modifier   provisions: goods output in place of food\nlaw_z.x  gone\n")
    found, unmatched = proposer.seed_keep_file(copies, devs, keep, "2026-10-02")
    assert unmatched == ["law_z.x"]
    rec = found[0]["record"]
    assert rec["address"]["path"] == [{"key": "modifier"}] and rec["scope"] == "subtree"
    assert rec["seen"]["mod_sig"] and rec["disposition"] == "keep_mod"


def test_seed_rules_takes_the_reason_from_the_named_note(tmp_path):
    mod, copies, devs = _world(tmp_path)
    rules = tmp_path / "rules.json"
    rules.write_text(json.dumps([dict(_rule(reason=""), reason_from="food cancels")]))
    notes = [{"id": "176", "title": "", "body": "- Goods output modifiers: food cancels, see laws.\n"}]
    cands = proposer.seed_rules(devs, rules, notes)
    assert cands[0]["record"]["reason"] == "Goods output modifiers: food cancels, see laws."
    assert cands[0]["selects"] == 1 and "reason_from" not in cands[0]["record"]


