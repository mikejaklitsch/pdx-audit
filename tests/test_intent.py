def test_identity_survives_a_move_to_another_mod_file(tmp_path):
    _m, _c, devs = _world(tmp_path / "a")
    a = {(d.identity, json.dumps(d.path), d.change) for d in devs if d.copy == "replace"}
    # the same REPLACE in another file name of the same folder
    mod_b = tmp_path / "c"
    _m, _c, other = _world(mod_b, extra={"in_game/common/laws/fe_laws.txt": "",
                                          "in_game/common/laws/zz_moved.txt": MOD_LAWS})
    b = {(d.identity, json.dumps(d.path), d.change) for d in other if d.copy == "replace"}
    assert a == b and a


