def test_cli_add_rule_list_propose_accept(tmp_path, monkeypatch, capsys):
    from pdxaudit.intent_cli import main
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "data"))
    mod, _c, _d = _world(tmp_path)
    repo = str(tmp_path / "vanilla-tracker" / "repo.git")
    common = ["--mod-root", str(mod), "--vanilla-repo", repo]
    rule = tmp_path / "rule.json"
    rule.write_text(json.dumps(_rule()))
    assert main(common + ["add-rule", str(rule)]) == 0
    assert main(common + ["--json", "list"]) == 0
    out = capsys.readouterr().out
    rows = json.loads(out[out.index("["):])
    assert rows[0]["id"] == "provisions.food_cancels" and rows[0]["covers"] == 1
    prop = tmp_path / "prop.json"
    assert main(common + ["propose", "--out", str(prop)]) == 0
    doc = json.loads(prop.read_text())
    assert doc["kind"] == proposer.PROPOSAL_KIND and doc["vanilla"] == "1.1"
    assert not any(m["mod"] and "local_monthly_food_modifier" in m["mod"]
                   for c in doc["candidates"] for m in c["members"])     # the rule explains it
    assert main(common + ["accept", str(prop), "--only", "c1"]) == 1   # no disposition chosen yet
    assert main(common + ["remove", "provisions.food_cancels"]) == 0


def test_every_override_prefix_is_a_copy(tmp_path):
    """TRY_REPLACE and REPLACE_OR_CREATE are REPLACE copies; TRY_INJECT and
    INJECT_OR_CREATE are INJECT copies."""
    extra = {"in_game/common/laws/fe_laws.txt": MOD_LAWS.replace("REPLACE:", "TRY_REPLACE:"),
             "in_game/common/laws/m.txt": "TRY_INJECT:law_b = {\n\tnew_key = yes\n}\n",
             "in_game/common/laws/n.txt": "REPLACE_OR_CREATE:law_c = {\n\tx = 1\n}\n"}
    _mod, _copies, devs = _world(tmp_path, extra=extra)
    assert _dev(devs, mod_key="local_monthly_food_modifier").copy == "replace"
    assert _dev(devs, mod_key="new_key").copy == "inject"
